package sealedtree

import (
	"bytes"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"io"
	"strconv"

	"github.com/wongyiuming/FrontierCloud-Gin/internal/mediacrypto"
	"github.com/wongyiuming/FrontierCloud-Gin/internal/protocol"
)

const placementPayloadBytes = 2048
const maxObjectBytes int64 = protocol.MaxOpaquePlainBytes

// Placement is trusted-Master in-memory metadata, never a wire format for an
// untrusted node or a plaintext persistent row. MediaID and blob identity are
// distinct. ReadAlias and BlobID must be independently generated by trusted
// Master code; hex validation alone cannot prove randomness. A node receives
// only the scoped alias/blob values, not this record or historical IDs.
// SHA256 describes stored bytes, ciphertext when Encryption is non-nil.
type Placement struct {
	ObjectID       string                `json:"object_id"`
	NativeObjectID string                `json:"native_object_id"`
	OwnerID        string                `json:"owner_id"`
	BlobID         string                `json:"blob_id"`
	ReadAlias      string                `json:"read_alias"`
	Bytes          int64                 `json:"bytes"`
	SHA256         string                `json:"sha256"`
	ETag           string                `json:"etag,omitempty"`
	State          string                `json:"state,omitempty"`
	CreatedAt      int64                 `json:"created_at,omitempty"`
	UpdatedAt      int64                 `json:"updated_at,omitempty"`
	Encryption     *mediacrypto.Metadata `json:"encryption,omitempty"`
}

// PlacementRecord is safe to persist only in a store that enforces encrypted
// row/revision identity, atomic lifecycle operations, and independent blob-ID
// uniqueness. It contains no business path, owner, raw ID, or descriptor.
type PlacementRecord struct {
	ObjectIndex string
	BlobIndex   string
	Revision    int64
	Sealed      []byte
}

func lowerHex(s string, length int) bool {
	if len(s) != length {
		return false
	}
	decoded, err := hex.DecodeString(s)
	return err == nil && hex.EncodeToString(decoded) == s
}

func validPlacement(p Placement) bool {
	empty := sha256.Sum256(nil)
	if !hexID(p.ObjectID) || !hexID(p.NativeObjectID) || !lowerHex(p.OwnerID, 32) || !hexID(p.BlobID) || p.BlobID == p.ObjectID || p.BlobID == p.NativeObjectID || !hexID(p.ReadAlias) || p.ReadAlias == p.BlobID || p.ReadAlias == p.ObjectID || p.ReadAlias == p.NativeObjectID || !hexID(p.SHA256) || p.Bytes < 0 || p.Bytes > maxObjectBytes || !factText(p.ETag, 512, true) || !factText(p.State, 32, true) {
		return false
	}
	if p.Bytes == 0 && p.SHA256 != hex.EncodeToString(empty[:]) {
		return false
	}
	return p.Encryption == nil || p.Encryption.Validate() == nil && p.Encryption.CiphertextSize == p.Bytes
}

// BlobIndex permits duplicate rejection across both blob IDs and read aliases
// without storing raw values. Both must originate from independent NewBlobID
// calls, not paths, content hashes or legacy IDs. Reservations are permanent.
func (t *Tree) BlobIndex(blobID string) (string, error) {
	if t == nil || !t.ready || !hexID(blobID) {
		return "", ErrInvalid
	}
	mac := hmac.New(sha256.New, t.indexKey[:])
	_, _ = mac.Write([]byte("frontiercloud:sealed-tree:blob:v1\x00" + blobID))
	return hex.EncodeToString(mac.Sum(nil)), nil
}

func placementAAD(objectIndex, blobIndex string, revision int64) []byte {
	return []byte("frontiercloud:sealed-tree:placement:v1\x00" + objectIndex + "\x00" + blobIndex + "\x00" + strconv.FormatInt(revision, 10))
}

// SealPlacement encrypts content placement and encryption attributes in a
// fixed-size row. It neither accesses nor verifies an actual payload file.
func (t *Tree) SealPlacement(p Placement, revision int64) (PlacementRecord, error) {
	if t == nil || !t.ready || !validPlacement(p) || revision <= 0 {
		return PlacementRecord{}, ErrInvalid
	}
	objectIndex, err := t.ObjectIndex(p.ObjectID)
	if err != nil {
		return PlacementRecord{}, err
	}
	blobIndex, err := t.BlobIndex(p.BlobID)
	if err != nil {
		return PlacementRecord{}, err
	}
	encoded, err := json.Marshal(p)
	if err != nil || len(encoded) == 0 || len(encoded) > placementPayloadBytes-2 {
		return PlacementRecord{}, ErrInvalid
	}
	defer clear(encoded)
	plain := make([]byte, placementPayloadBytes)
	defer clear(plain)
	binary.BigEndian.PutUint16(plain[:2], uint16(len(encoded)))
	copy(plain[2:], encoded)
	random := make([]byte, recordSaltBytes+nonceBytes)
	if _, err = io.ReadFull(rand.Reader, random); err != nil {
		return PlacementRecord{}, ErrInvalid
	}
	aead, err := t.recordCipher(random[:recordSaltBytes], "placement")
	if err != nil {
		return PlacementRecord{}, err
	}
	sealed := append([]byte{recordVersion}, random...)
	sealed = aead.Seal(sealed, random[recordSaltBytes:], plain, placementAAD(objectIndex, blobIndex, revision))
	return PlacementRecord{ObjectIndex: objectIndex, BlobIndex: blobIndex, Revision: revision, Sealed: sealed}, nil
}

// PlacementEncryptionID returns a nonsecret unique reservation value. It does
// not authenticate the record and must be checked inside the caller's atomic
// transaction before publishing any ciphertext or changing placement.
func PlacementEncryptionID(r PlacementRecord) (string, error) {
	if len(r.Sealed) != 1+recordSaltBytes+nonceBytes+placementPayloadBytes+16 || r.Sealed[0] != recordVersion {
		return "", ErrInvalid
	}
	return hex.EncodeToString(r.Sealed[1 : 1+recordSaltBytes]), nil
}

// OpenPlacement authenticates the complete owner/object/blob/descriptor state
// and rechecks its keyed tags. The caller must enforce current authorization,
// state, version, visibility, file identity and snapshot fencing separately.
func (t *Tree) OpenPlacement(r PlacementRecord) (Placement, error) {
	if t == nil || !t.ready || !hexID(r.ObjectIndex) || !hexID(r.BlobIndex) || r.Revision <= 0 || len(r.Sealed) != 1+recordSaltBytes+nonceBytes+placementPayloadBytes+16 || r.Sealed[0] != recordVersion {
		return Placement{}, ErrInvalid
	}
	salt := r.Sealed[1 : 1+recordSaltBytes]
	nonce := r.Sealed[1+recordSaltBytes : 1+recordSaltBytes+nonceBytes]
	aead, err := t.recordCipher(salt, "placement")
	if err != nil {
		return Placement{}, err
	}
	plain, err := aead.Open(nil, nonce, r.Sealed[1+recordSaltBytes+nonceBytes:], placementAAD(r.ObjectIndex, r.BlobIndex, r.Revision))
	if err != nil {
		return Placement{}, ErrInvalid
	}
	defer clear(plain)
	length := int(binary.BigEndian.Uint16(plain[:2]))
	if length == 0 || length > placementPayloadBytes-2 {
		return Placement{}, ErrInvalid
	}
	for _, value := range plain[2+length:] {
		if value != 0 {
			return Placement{}, ErrInvalid
		}
	}
	decoder := json.NewDecoder(bytes.NewReader(plain[2 : 2+length]))
	decoder.DisallowUnknownFields()
	var p Placement
	if err = decoder.Decode(&p); err != nil || !validPlacement(p) {
		return Placement{}, ErrInvalid
	}
	var extra any
	if err = decoder.Decode(&extra); err != io.EOF {
		return Placement{}, ErrInvalid
	}
	objectIndex, err := t.ObjectIndex(p.ObjectID)
	if err != nil || !hmac.Equal([]byte(objectIndex), []byte(r.ObjectIndex)) {
		return Placement{}, ErrInvalid
	}
	blobIndex, err := t.BlobIndex(p.BlobID)
	if err != nil || !hmac.Equal([]byte(blobIndex), []byte(r.BlobIndex)) {
		return Placement{}, ErrInvalid
	}
	return p, nil
}
